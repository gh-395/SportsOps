-- SportsOps relational schema for PostgreSQL 10+.

CREATE TABLE IF NOT EXISTS competitions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    country VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS seasons (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    competition_id INTEGER NOT NULL REFERENCES competitions(id) ON DELETE RESTRICT,
    name VARCHAR(20) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    CONSTRAINT uq_seasons_competition_name UNIQUE (competition_id, name),
    CONSTRAINT ck_seasons_dates CHECK (start_date <= end_date)
);

CREATE TABLE IF NOT EXISTS teams (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    country VARCHAR(100) NOT NULL,
    CONSTRAINT uq_teams_name_country UNIQUE (name, country)
);

CREATE TABLE IF NOT EXISTS matches (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_id VARCHAR(40) NOT NULL UNIQUE,
    season_id INTEGER NOT NULL REFERENCES seasons(id) ON DELETE RESTRICT,
    home_team_id INTEGER NOT NULL REFERENCES teams(id) ON DELETE RESTRICT,
    away_team_id INTEGER NOT NULL REFERENCES teams(id) ON DELETE RESTRICT,
    kickoff_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(20) NOT NULL,
    elapsed_minute SMALLINT,
    home_score SMALLINT,
    away_score SMALLINT,
    is_simulated BOOLEAN NOT NULL DEFAULT TRUE,
    data_origin VARCHAR(12) NOT NULL DEFAULT 'SYNTHETIC',
    source_name VARCHAR(120) NOT NULL DEFAULT 'SportsOps demo seed',
    source_reference VARCHAR(255),
    CONSTRAINT ck_matches_status
        CHECK (status IN ('SCHEDULED', 'LIVE', 'HALF_TIME', 'FINISHED')),
    CONSTRAINT ck_matches_nonnegative_scores
        CHECK ((home_score IS NULL OR home_score >= 0)
           AND (away_score IS NULL OR away_score >= 0)),
    CONSTRAINT ck_matches_distinct_teams CHECK (home_team_id <> away_team_id),
    CONSTRAINT ck_matches_elapsed_minute
        CHECK (elapsed_minute IS NULL OR elapsed_minute BETWEEN 0 AND 150),
    CONSTRAINT ck_matches_data_origin
        CHECK (data_origin IN ('SIMULATED', 'SYNTHETIC', 'HISTORICAL')),
    CONSTRAINT ck_matches_data_origin_simulated CHECK (
        (data_origin = 'HISTORICAL' AND is_simulated = FALSE)
        OR (data_origin IN ('SIMULATED', 'SYNTHETIC') AND is_simulated = TRUE)
    )
);

CREATE TABLE IF NOT EXISTS match_events (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id INTEGER NOT NULL REFERENCES matches(id) ON DELETE CASCADE,
    event_key VARCHAR(80) NOT NULL,
    minute SMALLINT NOT NULL,
    event_type VARCHAR(40) NOT NULL,
    team_id INTEGER REFERENCES teams(id) ON DELETE RESTRICT,
    description TEXT NOT NULL,
    is_simulated BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_match_events_match_key UNIQUE (match_id, event_key),
    CONSTRAINT ck_match_events_minute CHECK (minute BETWEEN 0 AND 150)
);

CREATE TABLE IF NOT EXISTS match_statistics (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id INTEGER NOT NULL REFERENCES matches(id) ON DELETE CASCADE,
    home_possession NUMERIC(5, 2) NOT NULL,
    away_possession NUMERIC(5, 2) NOT NULL,
    home_shots SMALLINT NOT NULL,
    away_shots SMALLINT NOT NULL,
    home_shots_on_target SMALLINT NOT NULL,
    away_shots_on_target SMALLINT NOT NULL,
    CONSTRAINT uq_match_statistics_match UNIQUE (match_id),
    CONSTRAINT ck_match_statistics_possession_range
        CHECK (home_possession BETWEEN 0 AND 100
           AND away_possession BETWEEN 0 AND 100),
    CONSTRAINT ck_match_statistics_nonnegative_shots
        CHECK (home_shots >= 0 AND away_shots >= 0
           AND home_shots_on_target >= 0 AND away_shots_on_target >= 0),
    CONSTRAINT ck_match_statistics_shots_on_target
        CHECK (home_shots_on_target <= home_shots
           AND away_shots_on_target <= away_shots)
);

CREATE TABLE IF NOT EXISTS data_quality_alerts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id INTEGER REFERENCES matches(id) ON DELETE SET NULL,
    rule_code VARCHAR(50) NOT NULL,
    severity VARCHAR(10) NOT NULL,
    message TEXT NOT NULL,
    detected_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    acknowledged_at TIMESTAMP WITH TIME ZONE,
    resolved_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_data_quality_alerts_severity
        CHECK (severity IN ('INFO', 'WARNING', 'ERROR'))
);

CREATE INDEX IF NOT EXISTS ix_matches_season_status ON matches (season_id, status);
CREATE INDEX IF NOT EXISTS ix_matches_home_team ON matches (home_team_id);
CREATE INDEX IF NOT EXISTS ix_matches_away_team ON matches (away_team_id);
CREATE INDEX IF NOT EXISTS ix_match_events_match_minute ON match_events (match_id, minute);
CREATE INDEX IF NOT EXISTS ix_data_quality_alerts_open
    ON data_quality_alerts (resolved_at, severity);

CREATE TABLE IF NOT EXISTS markets (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id INTEGER NOT NULL REFERENCES matches(id) ON DELETE RESTRICT,
    market_type VARCHAR(32) NOT NULL,
    status VARCHAR(12) NOT NULL DEFAULT 'OPEN',
    is_simulated BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_markets_match_type UNIQUE (match_id, market_type),
    CONSTRAINT ck_markets_type
        CHECK (market_type IN ('1X2', 'OVER_UNDER_2_5', 'BOTH_TEAMS_TO_SCORE')),
    CONSTRAINT ck_markets_status
        CHECK (status IN ('OPEN', 'SUSPENDED', 'CLOSED'))
);

CREATE TABLE IF NOT EXISTS market_selections (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    market_id INTEGER NOT NULL REFERENCES markets(id) ON DELETE RESTRICT,
    selection_key VARCHAR(20) NOT NULL,
    selection_name VARCHAR(100) NOT NULL,
    opening_odds NUMERIC(8, 3) NOT NULL,
    current_odds NUMERIC(8, 3) NOT NULL,
    CONSTRAINT uq_market_selections_market_key UNIQUE (market_id, selection_key),
    CONSTRAINT ck_market_selections_opening_odds CHECK (opening_odds > 1),
    CONSTRAINT ck_market_selections_current_odds CHECK (current_odds > 1)
);

CREATE TABLE IF NOT EXISTS odds_history (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    selection_id INTEGER NOT NULL
        REFERENCES market_selections(id) ON DELETE RESTRICT,
    previous_odds NUMERIC(8, 3) NOT NULL,
    current_odds NUMERIC(8, 3) NOT NULL,
    changed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    source VARCHAR(16) NOT NULL,
    is_simulated BOOLEAN NOT NULL DEFAULT TRUE,
    idempotency_key VARCHAR(100) NOT NULL,
    CONSTRAINT ck_odds_history_valid_odds
        CHECK (previous_odds > 1 AND current_odds > 1),
    CONSTRAINT ck_odds_history_source CHECK (source IN ('SIMULATION', 'RESET')),
    CONSTRAINT uq_odds_history_idempotency UNIQUE (idempotency_key)
);

CREATE TABLE IF NOT EXISTS trading_risk_alerts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    odds_history_id INTEGER NOT NULL
        REFERENCES odds_history(id) ON DELETE RESTRICT,
    severity VARCHAR(10) NOT NULL,
    description TEXT NOT NULL,
    detected_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    acknowledged_at TIMESTAMP WITH TIME ZONE,
    acknowledgement_note TEXT,
    is_simulated BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_trading_risk_alerts_history UNIQUE (odds_history_id),
    CONSTRAINT ck_trading_risk_alerts_severity
        CHECK (severity IN ('WARNING', 'ERROR'))
);

CREATE TABLE IF NOT EXISTS trading_audit_log (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    market_id INTEGER REFERENCES markets(id) ON DELETE RESTRICT,
    selection_id INTEGER REFERENCES market_selections(id) ON DELETE RESTRICT,
    odds_history_id INTEGER REFERENCES odds_history(id) ON DELETE RESTRICT,
    event_type VARCHAR(32) NOT NULL,
    old_value TEXT,
    new_value TEXT,
    reason TEXT NOT NULL,
    actor VARCHAR(100) NOT NULL DEFAULT 'Operator',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_simulated BOOLEAN NOT NULL DEFAULT TRUE,
    idempotency_key VARCHAR(120),
    CONSTRAINT ck_trading_audit_event_type CHECK (
        event_type IN (
            'MARKET_CREATED', 'ODDS_UPDATED', 'ODDS_RESET',
            'MARKET_SUSPENDED', 'MARKET_REOPENED',
            'RISK_ALERT_ACKNOWLEDGED', 'SIMULATION_STARTED',
            'SIMULATION_PAUSED', 'RISK_THRESHOLDS_CHANGED'
        )
    ),
    CONSTRAINT uq_trading_audit_idempotency UNIQUE (idempotency_key)
);

CREATE INDEX IF NOT EXISTS ix_markets_status_type ON markets (status, market_type);
CREATE INDEX IF NOT EXISTS ix_market_selections_market ON market_selections (market_id);
CREATE INDEX IF NOT EXISTS ix_odds_history_selection_time
    ON odds_history (selection_id, changed_at);
CREATE INDEX IF NOT EXISTS ix_trading_risk_alerts_ack_severity
    ON trading_risk_alerts (acknowledged_at, severity);
CREATE INDEX IF NOT EXISTS ix_trading_audit_market_time
    ON trading_audit_log (market_id, created_at);

CREATE OR REPLACE FUNCTION sportsops_reject_trading_audit_change()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'trading_audit_log is append-only';
END;
$$;

DROP TRIGGER IF EXISTS trg_trading_audit_no_mutation ON trading_audit_log;
CREATE TRIGGER trg_trading_audit_no_mutation
    BEFORE UPDATE OR DELETE ON trading_audit_log
    FOR EACH ROW EXECUTE FUNCTION sportsops_reject_trading_audit_change();

CREATE TABLE IF NOT EXISTS simulation_runs (
    run_id VARCHAR(32) PRIMARY KEY,
    seed INTEGER NOT NULL,
    speed SMALLINT NOT NULL DEFAULT 5,
    status VARCHAR(12) NOT NULL DEFAULT 'RUNNING',
    warning_percent NUMERIC(5, 2) NOT NULL DEFAULT 10,
    critical_percent NUMERIC(5, 2) NOT NULL DEFAULT 15,
    started_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_simulation_runs_status
        CHECK (status IN ('RUNNING', 'PAUSED', 'COMPLETED', 'RESET')),
    CONSTRAINT ck_simulation_runs_speed CHECK (speed IN (1, 5, 10)),
    CONSTRAINT ck_simulation_runs_risk_thresholds
        CHECK (warning_percent > 0 AND critical_percent >= warning_percent)
);

CREATE TABLE IF NOT EXISTS simulation_match_states (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id VARCHAR(32) NOT NULL
        REFERENCES simulation_runs(run_id) ON DELETE CASCADE,
    match_id INTEGER NOT NULL REFERENCES matches(id) ON DELETE RESTRICT,
    status VARCHAR(12) NOT NULL,
    minute SMALLINT NOT NULL,
    home_score SMALLINT NOT NULL,
    away_score SMALLINT NOT NULL,
    home_red_cards SMALLINT NOT NULL DEFAULT 0,
    away_red_cards SMALLINT NOT NULL DEFAULT 0,
    home_goal_rate NUMERIC(5, 3) NOT NULL,
    away_goal_rate NUMERIC(5, 3) NOT NULL,
    event_schedule TEXT NOT NULL,
    next_event_index INTEGER NOT NULL DEFAULT 0,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_simulation_match_state UNIQUE (run_id, match_id),
    CONSTRAINT ck_simulation_match_state_status
        CHECK (status IN ('SCHEDULED', 'LIVE', 'HALF_TIME', 'FINISHED')),
    CONSTRAINT ck_simulation_match_minute CHECK (minute BETWEEN 0 AND 90),
    CONSTRAINT ck_simulation_match_nonnegative
        CHECK (home_score >= 0 AND away_score >= 0
           AND home_red_cards >= 0 AND away_red_cards >= 0),
    CONSTRAINT ck_simulation_match_goal_rates
        CHECK (home_goal_rate > 0 AND away_goal_rate > 0)
);

CREATE TABLE IF NOT EXISTS simulation_events (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id VARCHAR(32) NOT NULL
        REFERENCES simulation_runs(run_id) ON DELETE CASCADE,
    match_id INTEGER NOT NULL REFERENCES matches(id) ON DELETE RESTRICT,
    event_key VARCHAR(120) NOT NULL,
    event_sequence INTEGER NOT NULL,
    minute SMALLINT NOT NULL,
    event_type VARCHAR(24) NOT NULL,
    team_id INTEGER REFERENCES teams(id) ON DELETE RESTRICT,
    description TEXT NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_simulation_event_key UNIQUE (run_id, match_id, event_key),
    CONSTRAINT uq_simulation_event_sequence
        UNIQUE (run_id, match_id, event_sequence),
    CONSTRAINT ck_simulation_event_minute CHECK (minute BETWEEN 0 AND 90)
);

CREATE TABLE IF NOT EXISTS simulation_market_controls (
    market_id INTEGER PRIMARY KEY REFERENCES markets(id) ON DELETE RESTRICT,
    manually_suspended BOOLEAN NOT NULL DEFAULT FALSE,
    suspension_reason TEXT,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS simulation_market_states (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id VARCHAR(32) NOT NULL
        REFERENCES simulation_runs(run_id) ON DELETE CASCADE,
    market_id INTEGER NOT NULL REFERENCES markets(id) ON DELETE RESTRICT,
    status VARCHAR(12) NOT NULL,
    suspension_kind VARCHAR(10) NOT NULL DEFAULT 'NONE',
    suspension_reason TEXT,
    reopen_after_minute SMALLINT,
    CONSTRAINT uq_simulation_market_state UNIQUE (run_id, market_id),
    CONSTRAINT ck_simulation_market_state_status
        CHECK (status IN ('OPEN', 'SUSPENDED', 'CLOSED')),
    CONSTRAINT ck_simulation_market_state_suspension_kind
        CHECK (suspension_kind IN ('NONE', 'MANUAL', 'EVENT', 'CLOSED'))
);

CREATE TABLE IF NOT EXISTS simulation_selection_quotes (
    run_id VARCHAR(32) NOT NULL
        REFERENCES simulation_runs(run_id) ON DELETE CASCADE,
    selection_id INTEGER NOT NULL
        REFERENCES market_selections(id) ON DELETE RESTRICT,
    market_id INTEGER NOT NULL REFERENCES markets(id) ON DELETE RESTRICT,
    decimal_odds NUMERIC(8, 3) NOT NULL,
    fair_probability NUMERIC(10, 9) NOT NULL,
    reason TEXT NOT NULL,
    event_id INTEGER REFERENCES simulation_events(id) ON DELETE RESTRICT,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (run_id, selection_id),
    CONSTRAINT ck_simulation_quote_odds CHECK (decimal_odds > 1),
    CONSTRAINT ck_simulation_quote_probability
        CHECK (fair_probability BETWEEN 0 AND 1)
);

CREATE TABLE IF NOT EXISTS simulation_odds_history (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id VARCHAR(32) NOT NULL
        REFERENCES simulation_runs(run_id) ON DELETE CASCADE,
    market_id INTEGER NOT NULL REFERENCES markets(id) ON DELETE RESTRICT,
    selection_id INTEGER NOT NULL
        REFERENCES market_selections(id) ON DELETE RESTRICT,
    event_id INTEGER REFERENCES simulation_events(id) ON DELETE RESTRICT,
    previous_odds NUMERIC(8, 3) NOT NULL,
    current_odds NUMERIC(8, 3) NOT NULL,
    fair_probability NUMERIC(10, 9) NOT NULL,
    percentage_change NUMERIC(9, 4) NOT NULL,
    cause_type VARCHAR(24) NOT NULL,
    reason TEXT NOT NULL,
    changed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    idempotency_key VARCHAR(160) NOT NULL UNIQUE,
    CONSTRAINT ck_simulation_odds_history_valid_odds
        CHECK (previous_odds > 1 AND current_odds > 1),
    CONSTRAINT ck_simulation_odds_history_probability
        CHECK (fair_probability BETWEEN 0 AND 1)
);

CREATE TABLE IF NOT EXISTS simulation_audit_log (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id VARCHAR(32) REFERENCES simulation_runs(run_id) ON DELETE RESTRICT,
    match_id INTEGER REFERENCES matches(id) ON DELETE RESTRICT,
    market_id INTEGER REFERENCES markets(id) ON DELETE RESTRICT,
    selection_id INTEGER REFERENCES market_selections(id) ON DELETE RESTRICT,
    event_id INTEGER REFERENCES simulation_events(id) ON DELETE RESTRICT,
    event_type VARCHAR(40) NOT NULL,
    old_value TEXT,
    new_value TEXT,
    reason TEXT NOT NULL,
    actor VARCHAR(100) NOT NULL DEFAULT 'Simulation',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    idempotency_key VARCHAR(160) UNIQUE
);

CREATE TABLE IF NOT EXISTS trading_risk_incidents (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id VARCHAR(32)
        REFERENCES simulation_runs(run_id) ON DELETE RESTRICT,
    match_id INTEGER NOT NULL REFERENCES matches(id) ON DELETE RESTRICT,
    market_id INTEGER NOT NULL REFERENCES markets(id) ON DELETE RESTRICT,
    selection_id INTEGER NOT NULL
        REFERENCES market_selections(id) ON DELETE RESTRICT,
    rule_code VARCHAR(40) NOT NULL,
    highest_severity VARCHAR(10) NOT NULL,
    description TEXT NOT NULL,
    occurrence_count INTEGER NOT NULL,
    first_seen_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_seen_at TIMESTAMP WITH TIME ZONE NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'OPEN',
    acknowledged_at TIMESTAMP WITH TIME ZONE,
    acknowledgement_note TEXT,
    cooldown_until TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_trading_risk_incidents_severity
        CHECK (highest_severity IN ('WARNING', 'ERROR')),
    CONSTRAINT ck_trading_risk_incidents_status
        CHECK (status IN ('OPEN', 'ACKNOWLEDGED', 'RESOLVED')),
    CONSTRAINT ck_trading_risk_incidents_count CHECK (occurrence_count > 0),
    CONSTRAINT ck_trading_risk_incidents_chronology
        CHECK (last_seen_at >= first_seen_at)
);

CREATE TABLE IF NOT EXISTS trading_risk_occurrences (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id INTEGER NOT NULL
        REFERENCES trading_risk_incidents(id) ON DELETE RESTRICT,
    legacy_alert_id INTEGER
        REFERENCES trading_risk_alerts(id) ON DELETE RESTRICT,
    simulation_odds_history_id INTEGER
        REFERENCES simulation_odds_history(id) ON DELETE RESTRICT,
    severity VARCHAR(10) NOT NULL,
    description TEXT NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_risk_occurrences_legacy_alert UNIQUE (legacy_alert_id),
    CONSTRAINT uq_risk_occurrences_simulation_history
        UNIQUE (simulation_odds_history_id),
    CONSTRAINT ck_risk_occurrences_one_source CHECK (
        (legacy_alert_id IS NOT NULL AND simulation_odds_history_id IS NULL)
        OR (legacy_alert_id IS NULL AND simulation_odds_history_id IS NOT NULL)
    ),
    CONSTRAINT ck_risk_occurrences_severity
        CHECK (severity IN ('WARNING', 'ERROR'))
);

CREATE INDEX IF NOT EXISTS ix_simulation_runs_created
