    ON trading_risk_incidents
       (run_id, match_id, market_id, selection_id, rule_code)
    WHERE status = 'OPEN';
CREATE INDEX IF NOT EXISTS ix_trading_risk_incidents_status_severity
    ON trading_risk_incidents (status, highest_severity);
CREATE INDEX IF NOT EXISTS ix_risk_occurrences_incident_time
    ON trading_risk_occurrences (incident_id, occurred_at);

