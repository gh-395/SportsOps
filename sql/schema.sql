    FOR EACH ROW EXECUTE FUNCTION sportsops_reject_simulation_ledger_change();
DROP TRIGGER IF EXISTS trg_simulationauditlog_no_mutation ON simulation_audit_log;
CREATE TRIGGER trg_simulationauditlog_no_mutation
    BEFORE UPDATE OR DELETE ON simulation_audit_log
    FOR EACH ROW EXECUTE FUNCTION sportsops_reject_simulation_ledger_change();
DROP TRIGGER IF EXISTS trg_tradingriskoccurrences_no_mutation
