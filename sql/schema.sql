CREATE TABLE IF NOT EXISTS historical_import_batches (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    competition_id INTEGER NOT NULL REFERENCES competitions(id) ON DELETE RESTRICT,
    season_id INTEGER NOT NULL REFERENCES seasons(id) ON DELETE RESTRICT,
    source_name VARCHAR(120) NOT NULL,
    source_url VARCHAR(2048) NOT NULL,
    reuse_terms TEXT NOT NULL,
    file_sha256 VARCHAR(64) NOT NULL,
    rows_seen INTEGER NOT NULL,
    imported_count INTEGER NOT NULL,
    duplicate_count INTEGER NOT NULL,
    invalid_count INTEGER NOT NULL,
    imported_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_historical_import_file_sha256 UNIQUE (file_sha256),
    CONSTRAINT ck_historical_import_rows_seen CHECK (rows_seen >= 0),
    CONSTRAINT ck_historical_import_counts
        CHECK (imported_count >= 0 AND duplicate_count >= 0 AND invalid_count >= 0)
);

CREATE TABLE IF NOT EXISTS historical_matches (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_key VARCHAR(64) NOT NULL,
    source_batch_id INTEGER NOT NULL
        REFERENCES historical_import_batches(id) ON DELETE RESTRICT,
    source_row_number INTEGER NOT NULL,
    season_id INTEGER NOT NULL REFERENCES seasons(id) ON DELETE RESTRICT,
    home_team_id INTEGER NOT NULL REFERENCES teams(id) ON DELETE RESTRICT,
    away_team_id INTEGER NOT NULL REFERENCES teams(id) ON DELETE RESTRICT,
    kickoff_date DATE NOT NULL,
    kickoff_time TIME,
    home_score SMALLINT NOT NULL,
    away_score SMALLINT NOT NULL,
    CONSTRAINT uq_historical_matches_match_key UNIQUE (match_key),
    CONSTRAINT ck_historical_matches_nonnegative_scores
        CHECK (home_score >= 0 AND away_score >= 0),
    CONSTRAINT ck_historical_matches_distinct_teams
        CHECK (home_team_id <> away_team_id)
);

CREATE INDEX IF NOT EXISTS ix_historical_import_season
    ON historical_import_batches (season_id, imported_at);
CREATE INDEX IF NOT EXISTS ix_historical_matches_season_date
    ON historical_matches (season_id, kickoff_date);
CREATE INDEX IF NOT EXISTS ix_historical_matches_home_team
    ON historical_matches (home_team_id);
CREATE INDEX IF NOT EXISTS ix_historical_matches_away_team
    ON historical_matches (away_team_id);
